a = int(input("Введите число a (не ноль): "))
b = int(input("Введите число b (не ноль): "))

a_sq = a ** 2
b_sq = b ** 2

sum_sq = a_sq + b_sq
diff_sq = a_sq - b_sq
prod_sq = a_sq * b_sq
div_sq = a_sq / b_sq

print("Сумма квадратов =", sum_sq)
print("Разность квадратов =", diff_sq)
print("Произведение квадратов =", prod_sq)
print("Частное квадратов =", div_sq)