day = int(input("Введите день (1-31): "))
month = int(input("Введите месяц (1-12): "))

days_dict = {
    1: "первое", 2: "второе", 3: "третье", 4: "четвертое", 5: "пятое",
    6: "шестое", 7: "седьмое", 8: "восьмое", 9: "девятое", 10: "десятое",
    11: "одиннадцатое", 12: "двенадцатое", 13: "тринадцатое", 14: "четырнадцатое",
    15: "пятнадцатое", 16: "шестнадцатое", 17: "семнадцатое", 18: "восемнадцатое",
    19: "девятнадцатое", 20: "двадцатое", 30: "тридцатое", 31: "тридцать первое"
}
for i in range(21, 30):
    days_dict[i] = "двадцать " + days_dict[i - 20]

months_dict = {
    1: "января", 2: "февраля", 3: "марта", 4: "апреля", 5: "мая", 6: "июня",
    7: "июля", 8: "августа", 9: "сентября", 10: "октября", 11: "ноября", 12: "декабря"
}

if day in days_dict and month in months_dict:
    print(days_dict[day], months_dict[month])
else:
    print("Неверно введен день или месяц")