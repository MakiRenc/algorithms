# Задание 8

num = int(input("Введите количество заданий (10-40): "))

tens_dict = {
    10: "десять", 11: "одиннадцать", 12: "двенадцать", 13: "тринадцать",
    14: "четырнадцать", 15: "пятнадцать", 16: "шестнадцать",
    17: "семнадцать", 18: "восемнадцать", 19: "девятнадцать"
}
decades = {2: "двадцать", 3: "тридцать", 4: "сорок"}
units = {1: "одно", 2: "два", 3: "три", 4: "четыре", 5: "пять", 6: "шесть",
         7: "семь", 8: "восемь", 9: "девять"}

if num < 20:
    num_str = tens_dict[num]
else:
    ten = num // 10  
    unit = num % 10  
    if unit == 0:
        num_str = decades[ten]
    else:
        num_str = decades[ten] + " " + units[unit]

if num % 10 == 1 and num != 11:
    word = "учебное задание"
elif num % 10 in [2, 3, 4] and num not in [12, 13, 14]:
    word = "учебных задания"
else:
    word = "учебных заданий"

print(num_str, word)