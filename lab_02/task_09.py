num = int(input("Введите число от 100 до 999: "))

hundreds = {
    1: "сто", 2: "двести", 3: "триста", 4: "четыреста",
    5: "пятьсот", 6: "шестьсот", 7: "семьсот", 8: "восемьсот", 9: "девятьсот"
}
tens = {
    1: "десять", 2: "двадцать", 3: "тридцать", 4: "сорок",
    5: "пятьдесят", 6: "шестьдесят", 7: "семьдесят", 8: "восемьдесят", 9: "девяносто"
}
units = {
    1: "один", 2: "два", 3: "три", 4: "четыре", 5: "пять",
    6: "шесть", 7: "семь", 8: "восемь", 9: "девять"
}
teens = {
    10: "десять", 11: "одиннадцать", 12: "двенадцать", 13: "тринадцать",
    14: "четырнадцать", 15: "пятнадцать", 16: "шестнадцать",
    17: "семнадцать", 18: "восемнадцать", 19: "девятнадцать"
}

if 100 <= num <= 999:
    h = num // 100       
    remainder = num % 100 

    result = hundreds[h]

    if remainder > 0:
        if remainder < 10:
            result += " " + units[remainder]
        elif remainder < 20:
            result += " " + teens[remainder]
        else:
            t = remainder // 10
            u = remainder % 10
            result += " " + tens[t]
            if u > 0:
                result += " " + units[u]
                
    print(result)
else:
    print("Число не входит в диапазон 100-999")