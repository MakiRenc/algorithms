x = int(input("Введите x (не 0): "))
y = int(input("Введите y (не 0): "))

if x > 0 and y > 0:
    print("Точка в 1-й четверти")
elif x < 0 and y > 0:
    print("Точка во 2-й четверти")
elif x < 0 and y < 0:
    print("Точка в 3-й четверти")
elif x > 0 and y < 0:
    print("Точка в 4-й четверти")
else:
    print("Точка лежит на оси (введены неверные данные)")